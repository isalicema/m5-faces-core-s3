from pathlib import Path
from PIL import Image, ImageDraw, ImageFont, ImageChops
from fontTools.pens.basePen import BasePen
from fontTools.svgLib.path import parse_path
import re, xml.etree.ElementTree as ET, math
root=Path(__file__).resolve().parents[1]
S=8
assets={}
def label(name,text,font_path,size,tracking=0):
    f=ImageFont.truetype(font_path,size*S)
    im=Image.new('L',(256*S,32*S));d=ImageDraw.Draw(im);x=4*S
    for ch in text:
        d.text((x,0),ch,font=f,fill=255)
        x+=d.textlength(ch,font=f)+tracking*S
    box=im.getbbox();im=im.crop(box);im=im.resize((math.ceil(im.width/S),math.ceil(im.height/S)),Image.Resampling.LANCZOS)
    assets[name]=im
label('collection','COLLECTION','/System/Library/Fonts/Supplemental/Impact.ttf',18,.35)
label('subtitle','COLLECTED PLAYLISTS','/System/Library/Fonts/Menlo.ttc',7,.12)
class Outline(BasePen):
    def __init__(self): super().__init__(None); self.contours=[];self.points=[]
    def _moveTo(self,p):self.points=[p]
    def _lineTo(self,p):self.points.append(p)
    def _curveToOne(self,p1,p2,p3):
        p0=self._getCurrentPoint()
        for n in range(1,25):
            t=n/24;u=1-t
            self.points.append(tuple(u**3*p0[i]+3*u*u*t*p1[i]+3*u*t*t*p2[i]+t**3*p3[i] for i in (0,1)))
    def _closePath(self):self.contours.append(self.points)
    def _endPath(self):self._closePath()
source=(root/'music_bridge/preview.html').read_text()
for name in ('refresh','collection'):
    node=ET.fromstring(re.search(r'<symbol id="paper-'+name+r'".*?</symbol>',source).group())
    size=13;im=Image.new('L',(size*S,size*S));d=ImageDraw.Draw(im);scale=size*S/256
    for shape in node:
        layer=Image.new("L",im.size);d=ImageDraw.Draw(layer)
        if shape.tag=='path':
            pen=Outline();parse_path(shape.attrib['d'],pen)
            for points in pen.contours:d.polygon([(x*scale,y*scale) for x,y in points],fill=255)
        elif shape.tag=='rect':
            x,y,w,h=[float(shape.attrib[k]) for k in ('x','y','width','height')];r=float(shape.attrib.get('rx',0));stroke=float(shape.attrib.get('stroke-width',0))
            d.rounded_rectangle(((x-stroke/2)*scale,(y-stroke/2)*scale,(x+w+stroke/2)*scale,(y+h+stroke/2)*scale),radius=(r+stroke/2)*scale,fill=255)
            if shape.attrib.get('fill')=='none':d.rounded_rectangle(((x+stroke/2)*scale,(y+stroke/2)*scale,(x+w-stroke/2)*scale,(y+h-stroke/2)*scale),radius=max(0,r-stroke/2)*scale,fill=0)
        elif shape.tag=='circle':
            x,y,r=[float(shape.attrib[k]) for k in ('cx','cy','r')];stroke=float(shape.attrib.get('stroke-width',0))
            d.ellipse(((x-r-stroke/2)*scale,(y-r-stroke/2)*scale,(x+r+stroke/2)*scale,(y+r+stroke/2)*scale),fill=255)
            if shape.attrib.get('fill')=='none':d.ellipse(((x-r+stroke/2)*scale,(y-r+stroke/2)*scale,(x+r-stroke/2)*scale,(y+r-stroke/2)*scale),fill=0)
        im=ImageChops.lighter(im,layer)
    assets['collectionEntry' if name=='collection' else name]=im.resize((size,size),Image.Resampling.LANCZOS)
lines=['// Generated by tools/build_shelf_assets.py from the approved preview symbols.',
'// Local Impact/Menlo alpha glyph derivatives; no font binaries. Icons: existing Phosphor SVGs (MIT).',
'#pragma once','#include <cstdint>','namespace music_shelf_assets {']
for name,im in assets.items():
    lines.append(f'inline constexpr int {name}Width={im.width},{name}Height={im.height};')
    lines.append('inline constexpr uint8_t '+name+'[] = {'+','.join(map(str,im.tobytes()))+'};')
lines.append('}')
(root/'src/MusicShelfAssets.h').write_text('\n'.join(lines)+'\n')

